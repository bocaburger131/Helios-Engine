/**
 * Get bank name from RTN
 * @param {string} rtn - 9-digit routing transit number
 * @returns {string|null} Bank name or null
 */
export function getBankFromRTN(rtn) {
  if (!rtn || typeof rtn !== 'string') return null;
  const cleaned = rtn.replace(/[^0-9]/g, '');
  if (cleaned.length !== 9) return null;
  return RTN_BANK_MAP[cleaned] || null;
}

/**
 * Get bank name from FDIC cert
 * @param {string} cert - FDIC certificate number
 * @returns {string|null} Bank name or null
 */
export function getBankFromFDIC(cert) {
  if (!cert || typeof cert !== 'string') return null;
  const cleaned = cert.replace(/[^0-9]/g, '');
  return FDIC_CERT_MAP[cleaned] || null;
}

